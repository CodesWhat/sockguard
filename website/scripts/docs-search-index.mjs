// Builds the page and heading index the not-found page searches, from the docs
// workspace's MDX sources. Generated output is committed and checked by
// src/lib/docs-search-index.test.mjs, so a docs change that moves a heading
// fails CI until the index is regenerated.
//
//   node scripts/docs-search-index.mjs          write src/lib/docs-search-index.generated.ts
//   node scripts/docs-search-index.mjs --check  exit 1 if the file is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const docsDir = join(here, "..", "..", "docs", "content", "docs");
export const outFile = join(here, "..", "src", "lib", "docs-search-index.generated.ts");

// github-slugger rules, which Fumadocs uses for heading anchors.
function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[^\p{L}\p{M}\p{N}\p{Pc} -]/gu, "")
    .replace(/ /g, "-");
}

function plainHeading(raw) {
  return raw
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/`/g, "")
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/\s*\[#[^\]]*\]\s*$/, "")
    .trim();
}

export function buildIndex() {
  const meta = JSON.parse(readFileSync(join(docsDir, "meta.json"), "utf8"));
  const pages = [];
  const items = [];

  for (const slug of meta.pages) {
    const source = readFileSync(join(docsDir, `${slug}.mdx`), "utf8");
    const front = /^---\n([\s\S]*?)\n---/.exec(source);
    const title = /^title:\s*(.+)$/m
      .exec(front?.[1] ?? "")?.[1]
      ?.trim()
      .replace(/^["']|["']$/g, "");
    if (!title) throw new Error(`docs/content/docs/${slug}.mdx has no title`);
    const pageIdx = pages.length;
    pages.push([title, slug === "index" ? "/docs" : `/docs/${slug}`]);
    items.push([pageIdx, "", ""]);

    const seen = new Map();
    let fenced = false;
    for (const line of source.slice(front ? front[0].length : 0).split("\n")) {
      if (/^\s*```/.test(line)) {
        fenced = !fenced;
        continue;
      }
      if (fenced) continue;
      const m = /^(#{2,4})\s+(.+?)\s*#*\s*$/.exec(line);
      if (!m) continue;
      const heading = plainHeading(m[2]);
      let anchor = slugify(heading);
      const n = seen.get(anchor) ?? 0;
      seen.set(anchor, n + 1);
      if (n > 0) anchor = `${anchor}-${n}`;
      items.push([pageIdx, heading, anchor]);
    }
  }
  return { pages, items };
}

export function render({ pages, items }) {
  const rows = (list) => list.map((row) => `  ${JSON.stringify(row)},`).join("\n");
  return `// Generated by scripts/docs-search-index.mjs from docs/content/docs. Do not edit.
export const DOCS_SEARCH_PAGES: [title: string, url: string][] = [
${rows(pages)}
];

// [pageIndex, heading ("" for the page itself), anchor]
export const DOCS_SEARCH_ITEMS: [page: number, heading: string, anchor: string][] = [
${rows(items)}
];
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const next = render(buildIndex());
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(outFile, "utf8");
    } catch {}
    if (current !== next) {
      console.error(
        "docs-search-index.generated.ts is stale. Run: node scripts/docs-search-index.mjs",
      );
      process.exit(1);
    }
  } else {
    writeFileSync(outFile, next);
  }
}
